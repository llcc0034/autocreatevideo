def _compilation_diagnostic(exc):
    """Expose bounded compiler-owned identifiers, never raw exception text."""
    from studio.services.execution_request_storage import ExecutionRequestSizeError
    if isinstance(exc, ExecutionRequestSizeError):
        return exc.diagnostic
    from studio.services.prompt_profiles import PromptProfileError
    messages = {
        "prompt_profile_generation_language_invalid": "字段语言策略配置无效",
        "prompt_profile_generation_language_context_missing": "缺少字段语言上下文",
        "prompt_profile_preserved_source_mismatch": "内容与冻结来源不一致",
        "prompt_profile_generation_value_required": "缺少必需内容",
        "prompt_profile_generation_value_validator_failed": "内容未通过字段校验",
    }
    key = getattr(exc, "field_key", None)
    if (not isinstance(exc, PromptProfileError) or exc.code not in messages
            or not isinstance(key, str) or not re.fullmatch(r"[A-Za-z0-9_.-]{1,128}", key)):
        return None
    return {"code": exc.code, "field_key": key,
        "message": f"字段 {key}：{messages[exc.code]}。尚未提交主调用，请检查该字段来源及策略后人工继续。"}


def schedule_authorized_asset_fields(preparation):
    """Creation's original root lock is held; no field approval or call here.

    Purely manual missing fields keep a null due time. An already authorized
    missing AI batch must not depend on a page refresh to start preparation.
    """
    if preparation.purpose == "resource_smoke":
        return  # Resource fixtures are supplied explicitly, not generated by implicit auxiliary instances.
    if preparation.status != "awaiting_input" or not nonproduction_preparation_root(preparation).allow_external_calls:
        return
    detail = read_execution_preparation_detail(preparation)
    missing = {(row["unit_key"], row["field_key"]) for row in detail.evaluation["outstanding_fields"] if row["action"] == "input"}
    batches = detail.resolved_inputs["field_requests"]
    if any(missing & {(row["unit_key"], row["field_contract"]["field_key"]) for row in batch["value"]["items"]} for batch in batches):
        preparation.next_check_at = timezone.now()
        preparation.save(update_fields=("next_check_at", "updated_at"))


def _finalize_asset_field_phase(preparation, actor):
    collector, dispatcher = collect_asset_execution_admission, dispatch_asset_execution
    if preparation.deployment_smoke_id or preparation.workflow_smoke_id:
        from studio.services.execution_smoke_admission import collect_smoke_execution_admission
        from studio.services.execution_smoke_dispatch import dispatch_smoke_execution
        collector, dispatcher = collect_smoke_execution_admission, dispatch_smoke_execution
    if preparation.status == "preparing" and not preparation.reason_code:
        preparation = _finalize_or_record_invalid_request(preparation, actor, collector)
    if preparation.status == "ready" or (preparation.request_frozen_at and preparation.reason_code == "execution_resource_confirmation_required"):
        dispatcher(preparation_id=preparation.pk, expected_preparation_revision=preparation.revision, actor=actor)
        preparation.refresh_from_db()
    return preparation


def _finalize_or_record_invalid_request(preparation, actor, collector):
    """Keep a local compile failure visible without retrying unchanged inputs.

    The evaluated field phase may already have advanced this preparation's
    revision. Record against that exact basis, not the scanner's older claim;
    never overwrite concurrent edits or a newly frozen request.
    """
    basis = preparation.revision
    try:
        return finalize_execution(preparation_id=preparation.pk, expected_preparation_revision=basis,
            actor=actor, collect_admission_facts=collector)
    except ValidationError as exc:
        if getattr(exc, "code", None) == "execution_preparation_conflict":
            raise
        with _locked_preparations([preparation.pk], actor) as rows:
            current = rows[str(preparation.pk)]
            if current.revision != basis or current.request_frozen_at is not None or current.status == "cancelled":
                raise
            detail = read_execution_preparation_detail(current)
            current.revision += 1
            current.evaluation_revision = current.revision
            current.evaluated_at = timezone.now()
            current.status = "blocked"
            from studio.services.execution_request_storage import ExecutionRequestStorageError
            storage_failure = isinstance(exc, ExecutionRequestStorageError)
            current.reason_code = "execution_request_storage_invalid" if storage_failure else "execution_request_invalid"
            current.reason = ("完整请求的正式存储或完整性校验失败，尚未提交主调用。请检查请求大小边界及文件存储后人工继续；已确认字段不需要重新生成。"
                if storage_failure else "请求组装未通过校验，尚未提交主调用。请检查输入、参考素材类别／用途及策略配置后人工继续。")
            diagnostic = None if storage_failure else _compilation_diagnostic(exc)
            if diagnostic:
                current.reason = diagnostic["message"]
            current.next_check_at = None
            assign_json_contract(detail, "evaluation", {"schema_version": 1, "phase": "request_storage" if storage_failure else "compilation",
                "status": current.status, "reason_code": current.reason_code, "reason": current.reason,
                "preparation_revision": current.revision, "basis_preparation_revision": basis,
                "evaluated_at": current.evaluated_at.isoformat(),
                **({"diagnostic": diagnostic} if diagnostic else {})}, max_bytes=execution_configuration_max_bytes())
            current.full_clean()
            detail.clean()
            current.save()
            detail.save()
            current.contract = detail
            return current


def _defer_unchanged_missing_smoke(preparation):
    """Preserve an unchanged admission wait under the caller's root/prep locks.

    Both a direct scheduler scan and a parent coordinator use this same path.
    Only reschedule: no new admission fact, field approval or dispatch permit.
    New evidence, edits or policies still require complete evaluation.
    """
    from studio.services.execution_definitions import execution_definition_version
    from studio.services.execution_policy_configuration import read_execution_policies
    from studio.services.execution_preparations import preparation_execution_definition
    from studio.services.execution_smoke_evidence import read_instance_smoke_facts

    if (preparation.status != "blocked" or preparation.reason_code != "execution_smoke_missing"
            or preparation.evaluation_revision != preparation.revision or preparation.request_frozen_at is not None
            or not preparation.asset_job_id or preparation.asset_job.status != "preparing"
            or preparation.asset_job.ignore_late_result or not preparation.asset_job.owner.is_active):
        return False
    detail = read_execution_preparation_detail(preparation)
    policies = read_execution_policies()
    if detail.evaluation.get("phase") != "admission" or detail.evaluation.get("configuration") != policies.configuration.value:
        return False
    definition = preparation_execution_definition(preparation, detail=detail, current=True)
    version = execution_definition_version(preparation.execution_instance_version_id)
    if read_instance_smoke_facts(version, definition):
        return False
    preparation.next_check_at = timezone.now() + timedelta(seconds=policies.recheck_interval_seconds)
    preparation.save(update_fields=("next_check_at", "updated_at"))
    return True


@security_boundary_resolution_cache()
def advance_execution_preparation(*, preparation_id, expected_preparation_revision, actor, human_initiated=False):
    """Same owner-bound advance action for API and original worker scan.

    It never invents a field approval. Configured production retries use the
    same dispatch path; exhausted/unsafe failures require explicit handling.
    """
    if type(expected_preparation_revision) is not int or expected_preparation_revision < 1:
        raise ValidationError("必须提交明确的准备修订号")
    with _locked_preparations([preparation_id], actor) as rows:
        preparation = rows[str(preparation_id)]
        if preparation.revision != expected_preparation_revision:
            raise ValidationError("准备已变化，请重新读取后继续", code="execution_preparation_conflict")
        if not human_initiated and _defer_unchanged_missing_smoke(preparation):
            return preparation
        if preparation.reason_code in {"execution_resource_confirmation_required", "execution_auxiliary_review_required", "execution_request_invalid", "execution_request_storage_invalid"} and not human_initiated:
            return preparation
        production = bool(preparation.stage_run_id)
        child = bool(preparation.asset_job_id and preparation.asset_job.parent_preparation_id)
        frozen = preparation.request_frozen_at is not None
    if production:
        from studio.services.execution_production_admission import collect_production_execution_admission
        from studio.services.execution_production_dispatch import dispatch_production_execution
        if preparation.status == "cancelled":
            return preparation
        if not frozen:
            from studio.services.execution_auxiliary_requests import read_production_field_context
            from studio.services.execution_production_auxiliaries import reconcile_production_preparation_fields, production_field_children
            auxiliary = read_production_field_context(preparation)
            if auxiliary is not None:
                preparation = evaluate_preparation_fields(preparation_id=preparation.pk,
                    expected_preparation_revision=preparation.revision, actor=actor)
            else:
                preparation = reconcile_production_preparation_fields(preparation_id=preparation.pk,
                    expected_preparation_revision=preparation.revision, actor=actor)
                for pending in production_field_children(preparation):
                    if pending.status not in {"dispatched", "cancelled"}:
                        advance_execution_preparation(preparation_id=pending.pk, expected_preparation_revision=pending.revision, actor=actor, human_initiated=human_initiated)
                preparation.refresh_from_db()
            if preparation.status == "preparing" and not preparation.reason_code:
                preparation = _finalize_or_record_invalid_request(preparation, actor, collect_production_execution_admission)
        if preparation.status == "ready" or (frozen and preparation.reason_code == "execution_resource_confirmation_required"):
            dispatch_production_execution(preparation_id=preparation.pk, expected_preparation_revision=preparation.revision, actor=actor)
            preparation.refresh_from_db()
        if frozen and preparation.status != "cancelled":
            from studio.services.production_execution_recovery import advance_primary_retry
            advance_primary_retry(preparation, actor)
            preparation.refresh_from_db()
        return preparation
    if frozen:
        if preparation.status == "ready" or preparation.reason_code == "execution_resource_confirmation_required":
            preparation = _finalize_asset_field_phase(preparation, actor)
        return preparation
    if child or preparation.purpose == "resource_smoke":
        if preparation.status == "cancelled":
            return preparation
        preparation = evaluate_preparation_fields(preparation_id=preparation.pk,
            expected_preparation_revision=preparation.revision, actor=actor)
        return _finalize_asset_field_phase(preparation, actor)
    preparation = reconcile_asset_preparation_fields(preparation_id=preparation.pk,
        expected_preparation_revision=preparation.revision, actor=actor)
    if preparation.status == "cancelled" or nonproduction_preparation_root(preparation).status != "preparing":
        return preparation
    # Only the exact, nonterminal children already allocated by the existing
    # reconciliation phase. Their definitions forbid recursive auxiliaries.
    children = list(ExecutionPreparation.objects.filter(asset_job__parent_preparation=preparation,
        asset_job__status="preparing", asset_job__claim_token__isnull=True).order_by("id"))
    for pending in children:
        advance_execution_preparation(preparation_id=pending.pk, expected_preparation_revision=pending.revision,
            actor=actor, human_initiated=human_initiated)
    preparation.refresh_from_db()
    return _finalize_asset_field_phase(preparation, actor)
