"""Independent M1 fields of a saved M2 shot, without another body schema.

The caller has verified the original ScriptRevisionStructure. Only its saved
structure, values, defaults and mapping evidence are used. No parsing, registry
lookup, name matching, default injection or prompt composition happens here.
"""
from copy import deepcopy

from django.core.exceptions import ValidationError

from studio.services.data_structures import _value_path, validate_data_structure_snapshot
from studio.services.json_contracts import JsonExpansionBudget
from studio.services.structure_paths import MISSING, nonnull_schema


def _within(path, parent):
    # Paths are generated by the common path renderer, not evaluated as code.
    return path == parent or path.startswith(parent + ".") or path.startswith(parent + "[")


def _shot_scopes(episode_index, shot_index, origins):
    target = f"value.episodes[{episode_index}].shots[{shot_index}]"
    parents = (target, f"value.episodes[{episode_index}].shots",
        f"value.episodes[{episode_index}]", "value.episodes", "value")
    scopes = []
    for index, parent in enumerate(parents):
        # An explicit each binds this item to this source row. Do not use an
        # episode-level each to guess a renamed/constructed shot collection.
        if index == 1 and parent + ".source" in origins:
            origin = origins[parent + ".source"]
            if origin.get("source_path") is not None:
                scopes.append(origin["source_path"] + f"[{shot_index}]")
            break
        if parent in origins:
            origin = origins[parent]
            if origin.get("source_path") is not None:
                scopes.append(origin["source_path"] + target[len(parent):])
            break  # A literal ancestor is not an authored source object.
    # Explicit root/lookup leaves can live outside the item. Include exactly
    # those fields, not their siblings or the lookup's search/key inputs.
    scopes.extend(origin["source_path"] for path, origin in origins.items()
        if _within(path, target) and origin.get("source_path") is not None)
    return list(dict.fromkeys(scopes))


def storyboard_source_fields(document, *, max_bytes):
    """Return per-coordinate fields; original detail remains the sole store.

    Exact node/path distinguishes repeated uses of the same field definition.
    Missing, null, blank, false, zero and empty collections remain distinct.
    Values already resolved by M2 retain explicit configured-default evidence;
    they are never relabelled as model/human-authored values. Unknown extra keys
    stay in the original document but cannot acquire a fabricated field ID.
    """
    saved = document["structure"]["document"]
    projection = saved["projection"]
    structure = saved["output"]["data_structure"]
    schema = validate_data_structure_snapshot(structure)
    budget = JsonExpansionBudget(max_bytes, path="storyboard.source_fields")
    # Hold references while indexing; copy only the selected field rows below.
    indexed, children, pending = {}, {}, [(schema, projection["source_value"], [], "source", None)]
    while pending:
        schema, value, tokens, location, parent = pending.pop()
        base = nonnull_schema(schema)
        budget.consume({"path": location})
        indexed[location] = (base, value, tokens, len(indexed))
        children.setdefault(parent, []).append(location)
        if isinstance(value, dict) and base.get("type") == "object":
            pending.extend(reversed([(child, value.get(key, MISSING), [*tokens, key], _value_path(location, key), location)
                for key, child in base.get("properties", {}).items()]))
        elif isinstance(value, list) and base.get("type") == "array":
            pending.extend(reversed([(base["items"], child, [*tokens, index], _value_path(location, index), location)
                for index, child in enumerate(value)]))
    # Mapping lookup emits search/key evidence before its final selected path.
    origins = {row["path"]: row for row in projection["provenance"]}
    defaults = [row["path"] for row in projection["defaults"]]
    result = {}
    for episode_index, episode in enumerate(projection["value"]["episodes"]):
        for shot_index, shot in enumerate(episode["shots"]):
            scopes = _shot_scopes(episode_index, shot_index, origins)
            selected, pending = set(), list(scopes)
            while pending:
                location = pending.pop()
                if location not in indexed:
                    raise ValidationError({location: "保存的分镜映射来源不在原结构字段中，不能忽略或猜测替代字段"})
                if location not in selected:
                    selected.add(location)
                    pending.extend(children.get(location, []))
            fields = []
            for location in sorted(selected, key=lambda key: indexed[key][3]):
                base, value, tokens, _ = indexed[location]
                definition = base.get("x-field-definition")
                if definition is None:
                    continue
                inherited = [path for path in defaults if _within(location, path)]
                applied = [path for path in defaults if _within(path, location) or path in inherited]
                record = {"structure_version_id": structure["id"], "node_key": base["x-node-key"],
                    "field_definition": definition, "source_path": location, "value_path": tokens,
                    "present": value is not MISSING, "source_present": value is not MISSING and not inherited,
                    "default_paths": applied}
                if value is not MISSING:
                    record["value"] = value
                budget.consume(record)
                fields.append(deepcopy(record))
            result[episode["episode"], shot["shot"]] = fields
    return result


def read_bound_shot_field_contract(*, shot_id, project_id, max_bytes):
    """Read the bound original revision, never today's Run or field registry.

    Missing binding is explicit: older/manual fixed-column shots are not
    converted into authored structured values. Consumers must request this
    detail, rather than hydrating every shot list with complete source JSON.
    """
    from studio.models import ShotScriptSource
    from studio.services.script_revision_structures import read_script_revision_structure, script_structure_max_bytes

    source = ShotScriptSource.objects.filter(shot_id=shot_id, shot__episode__project_id=project_id,
        stage__production_run__project_id=project_id, stage__stage_key="storyboard").values(
            "shot_id", "structure_id", "stage_id", "episode_number", "shot_number",
            "document_sha256", "materialization_sha256").first()
    if source is None:
        raise ValidationError("镜头缺少本项目的确切结构化来源绑定", code="storyboard_source_missing")
    detail = read_script_revision_structure(revision_id=source["structure_id"], project_id=project_id, max_bytes=max_bytes)
    if detail["document_sha256"] != source["document_sha256"]:
        raise ValidationError("镜头绑定的原结构化内容已变化，不能改读当前版本", code="storyboard_source_conflict")
    fields = storyboard_source_fields({"structure": detail}, max_bytes=script_structure_max_bytes())
    coordinate = (source["episode_number"], source["shot_number"])
    if coordinate not in fields:
        raise ValidationError("原结构化修订中缺少绑定的镜头坐标", code="storyboard_source_conflict")
    return ({"source": {**source, **{key: str(source[key]) for key in ("shot_id", "structure_id", "stage_id")}},
        "fields": fields[coordinate]}, detail["document"]["output"]["data_structure"])


def read_shot_source_fields(*, shot_id, project_id, max_bytes):
    return read_bound_shot_field_contract(shot_id=shot_id, project_id=project_id, max_bytes=max_bytes)[0]
