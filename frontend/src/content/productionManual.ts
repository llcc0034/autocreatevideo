export const searchableManualText = (step: ManualStep) => [
  step.title, step.summary, step.location, step.next,
  ...step.keywords, ...step.inputs.flatMap((item) => [item.label, item.example, item.note]),
  ...step.actions, ...step.success, ...(step.cautions || []),
].join(' ').toLocaleLowerCase('zh-CN')

export const searchableIncidentText = (incident: ManualIncident) => [
  incident.symptom, incident.likelyCause, incident.confirmation,
  ...incident.actions, ...incident.keywords,
].join(' ').toLocaleLowerCase('zh-CN')
